-- =====================================================================
--  אילו יישובים קיימים בנתונים
--
--  לפני שמחלקים לסניפים צריך לדעת מה באמת כתוב בשדה. היישוב נשמר
--  בתוך notes בצורה "יישוב · בית ספר", ולכן החלק שלפני המפריד הוא
--  מה שהוקלד בטופס — על כל השגיאות, הקיצורים וצורות הכתיב שבו.
--
--  שים לב לשלושה דברים בפלט:
--    • אותו יישוב בכמה כתיבים ("פרדס חנה", "פרדס חנה כרכור",
--      "פרדס-חנה") — כל צורה צריכה להיכנס למיפוי בנפרד.
--    • שורות שנראות כמו בית ספר ולא כמו יישוב. זה קורה כשהנרשם
--      לא מילא יישוב: concat_ws מדלג על הריק, ובית הספר נשאר
--      ראשון. הן פשוט לא ייכנסו לרשימת הסניף.
--    • "(לא צוין)" — מי שאין לו יישוב בכלל, ולכן אי אפשר לשייך
--      אותו גיאוגרפית.
--
--  קורא בלבד. לא משנה כלום.
-- =====================================================================

select
  coalesce(
    nullif(btrim(split_part(coalesce(notes, ''), ' · ', 1)), ''),
    '(לא צוין)'
  )                                                      as "יישוב",
  count(*)                                               as "סה״כ",
  count(*) filter (
    where status = 'active' and do_not_contact = false
  )                                                      as "בני פנייה"
from people
group by 1
order by 2 desc;


-- ---------------------------------------------------------------------
-- כמה בכלל אפשר לשייך
-- ---------------------------------------------------------------------

select
  count(*)                                                        as "סה״כ פעילים",
  count(*) filter (where notes is null or btrim(notes) = '')      as "בלי שום פרט",
  count(*) filter (where notes like '%·%')                        as "יישוב ובית ספר",
  count(*) filter (where notes is not null and btrim(notes) <> ''
                     and notes not like '%·%')                    as "שדה אחד בלבד"
from people
where status = 'active' and do_not_contact = false;
