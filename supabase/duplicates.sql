-- =====================================================================
--  איתור כפילויות ברשימה
--
--  למה זה קורה בכלל: הייחודיות במסד היא על מספר הטלפון, לא על השם.
--  phone_e164 מוגדר unique, ולכן אותו מספר פיזית לא יכול להיכנס
--  פעמיים. אדם שמופיע פעמיים או שלוש נמצא במסד עם שני מספרים שונים
--  או יותר — נרשם שוב עם מספר של הורה, טעה בספרה, או נרשם פעם
--  מהנייד ופעם מהבית.
--
--  לכן נרמול לא יכול לפתור את זה: שני מספרים שונים נשארים שונים
--  גם אחרי הנרמול הכי טוב. צריך להחליט מי אותו אדם — וזו החלטה
--  שדורשת עין אנושית, כי "רון אבידן" בשכבה י' ו"רון אבידן" בשכבה ט'
--  הם כנראה באמת שני אנשים.
--
--  הקובץ הזה רק מסתכל. הוא לא משנה כלום.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. כמה זה בכלל
-- ---------------------------------------------------------------------

with dup as (
  select full_name, count(*) as n
    from people
   where status = 'active' and do_not_contact = false
   group by full_name
  having count(*) > 1
)
select
  (select count(*) from people
    where status = 'active' and do_not_contact = false)  as "ברשימה",
  (select count(*) from dup)                             as "שמות כפולים",
  (select coalesce(sum(n - 1), 0) from dup)              as "שיחות מיותרות";


-- ---------------------------------------------------------------------
-- 2. מי כפול, ולמה
--
--    מספרים דומים מאוד = טעות הקלדה, אותו אדם.
--    שכבות שונות = כנראה שני אנשים שונים עם אותו שם.
--    "שיחות שתועדו" חשוב: רשומה שכבר דיברו איתה לא מוחקים.
-- ---------------------------------------------------------------------

select
  p.full_name                                                   as "שם",
  count(*)                                                      as "רשומות",
  string_agg(p.phone_e164, '  |  ' order by p.created_at)        as "מספרים",
  string_agg(coalesce(p.grade, '–'), '  |  ' order by p.created_at)
                                                                as "שכבה",
  string_agg(coalesce(p.consent_source, '–'), '  |  ' order by p.created_at)
                                                                as "מקור",
  sum(t.calls)                                                  as "שיחות שתועדו"
from people p
left join lateral (
  select count(*) as calls
    from contacts c
    join assignments a on a.id = c.assignment_id
   where a.person_id = p.id
) t on true
where p.status = 'active' and p.do_not_contact = false
group by p.full_name
having count(*) > 1
order by count(*) desc, p.full_name;


-- ---------------------------------------------------------------------
-- 3. מספרים שלא עברו נרמול
--
--    אמור להחזיר אפס. אם לא — מישהו הכניס שורות ישירות לטבלה
--    בלי שהטריגר של normalize-on-write.sql היה מותקן, ואז יש
--    כפילויות אמיתיות של אותו מספר בשתי צורות כתיבה.
-- ---------------------------------------------------------------------

select count(*) as "מספרים לא מנורמלים"
  from people
 where phone_e164 !~ '^\+[1-9][0-9]{7,14}$';


-- ---------------------------------------------------------------------
-- 4. מה הטלפנים באמת רואים בקמפיין הפעיל
--
--    זו הרשימה שממנה מחלקים כרטיסים. אם שם מופיע כאן פעמיים,
--    שני טלפנים שונים יתקשרו לאותו אדם.
-- ---------------------------------------------------------------------

select
  p.full_name                                     as "שם",
  count(*)                                        as "כרטיסים פתוחים",
  string_agg(p.phone_e164, '  |  ')               as "מספרים"
from assignments a
join people p on p.id = a.person_id
where a.event_id = active_event()
  and a.state = 'pending'
group by p.full_name
having count(*) > 1
order by count(*) desc;
