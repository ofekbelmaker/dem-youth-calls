-- =====================================================================
--  יצירת פעולה חדשה
--
--  ערוך את ארבע השורות בבלוק הראשון והרץ הכל.
--  התוצאה: פעולה חדשה + כל הפעילים הפעילים במאגר המשותף שלה.
--
--  אפשר להריץ שוב ושוב — לכל הרצה נוצרת פעולה נוספת.
-- =====================================================================

do $$
declare
  ------------------------------------------------------------------
  -- ✏️  כאן עורכים
  ------------------------------------------------------------------
  v_title    text        := 'פעולת פתיחת שנה';
  v_when     timestamptz := '2026-08-19 18:30';   -- שנה-חודש-יום שעה
  v_where    text        := 'בית התנועה, תל אביב';
  v_target   integer     := 60;                    -- כמה מגיעים אנחנו רוצים
  ------------------------------------------------------------------

  v_event uuid;
  v_count integer;
begin
  insert into events (title, starts_at, location, target_count, assignment_strategy)
  values (v_title, v_when, v_where, v_target, 'pool')
  returning id into v_event;

  /* ממלא את המאגר המשותף בכל מי שמותר לפנות אליו —
     בלי מי שעזב ובלי מי שביקש שלא יפנו אליו */
  v_count := generate_assignments(v_event);

  raise notice 'נוצרה הפעולה "%" עם % שיחות במאגר', v_title, v_count;
end;
$$;


-- ---------------------------------------------------------------------
-- אימות: הפעולות שקיימות ומצב כל אחת
-- ---------------------------------------------------------------------

select
  e.title                                                  as "פעולה",
  to_char(e.starts_at, 'DD/MM/YYYY HH24:MI')               as "מתי",
  e.target_count                                           as "יעד",
  count(a.id)                                              as "שיחות",
  count(a.id) filter (where a.state = 'done')              as "בוצעו"
from events e
left join assignments a on a.event_id = e.id
group by e.id
order by e.starts_at desc;


