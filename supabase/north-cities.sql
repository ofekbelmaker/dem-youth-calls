-- =====================================================================
--  היישובים של סניף חיפה והצפון
--
--  הרשימה למטה היא טיוטה, לא אמת. היא נכתבה מתוך גיאוגרפיה —
--  "פרדס חנה-כרכור וצפונה" — ולא מתוך מה שבאמת מוקלד אצלך בטופס.
--
--  לכן הסדר הנכון:
--    1. הרץ את city-survey.sql וראה אילו מחרוזות קיימות באמת.
--    2. הרץ את הקובץ הזה.
--    3. הרץ את הבדיקה שבסוף — היא מראה יישובים שקיימים בנתונים
--       ואינם משויכים לאף סניף. כל אחד מהם הוא או דרומי (ואז
--       הכול בסדר) או כתיב שלא חשבנו עליו (ואז צריך להוסיף).
--
--  למה כל כתיב בנפרד: ההתאמה היא מחרוזת מול מחרוזת. "פרדס חנה"
--  ו-"פרדס-חנה" הם שני ערכים שונים עבור המסד, ולכן שניהם ברשימה.
--  זה מכוער ועובד, וזו העדפה מודעת על פני התאמה חכמה שתשייך
--  בטעות יישוב שלא התכוונו אליו.
-- =====================================================================

insert into branch_cities (branch_id, city)
select b.id, c.city
  from branches b
  cross join (values
    -- ── פרדס חנה והסביבה ──
    ('פרדס חנה-כרכור'), ('פרדס חנה כרכור'), ('פרדס-חנה כרכור'),
    ('פרדס חנה'), ('פרדס-חנה'), ('כרכור'),
    ('בנימינה-גבעת עדה'), ('בנימינה'), ('גבעת עדה'),
    ('זכרון יעקב'), ('זיכרון יעקב'), ('זכרון'),
    ('אור עקיבא'), ('קיסריה'), ('ג׳סר א-זרקא'), ('גסר א-זרקא'),

    -- ── חיפה והקריות ──
    ('חיפה'), ('נשר'), ('טירת כרמל'), ('טירת הכרמל'), ('עתלית'),
    ('קריית אתא'), ('קרית אתא'), ('קריית ביאליק'), ('קרית ביאליק'),
    ('קריית מוצקין'), ('קרית מוצקין'), ('קריית ים'), ('קרית ים'),
    ('קריית חיים'), ('קרית חיים'), ('הקריות'), ('קריות'),
    ('קריית טבעון'), ('קרית טבעון'), ('טבעון'),
    ('דלית אל כרמל'), ('דאלית אל כרמל'), ('עוספיא'), ('עספיא'),

    -- ── עמקים וגליל ──
    ('יקנעם'), ('יקנעם עילית'), ('רמת ישי'), ('כפר יהושע'),
    ('עפולה'), ('מגדל העמק'), ('בית שאן'), ('עמק יזרעאל'),
    ('נצרת'), ('נוף הגליל'), ('נצרת עילית'),
    ('שפרעם'), ('טמרה'), ('סכנין'), ('כפר כנא'), ('אעבלין'),

    -- ── גליל מערבי וצפון ──
    ('עכו'), ('נהריה'), ('כרמיאל'), ('מעלות-תרשיחא'), ('מעלות'),
    ('שלומי'), ('צפת'), ('חצור הגלילית'), ('ראש פינה'),
    ('קריית שמונה'), ('קרית שמונה'), ('טבריה'), ('קצרין'),
    ('מטולה'), ('יסוד המעלה')

    -- ── גבוליים: חדרה דרומית לפרדס חנה. הסר את ההערה אם שייכת ──
    -- , ('חדרה'), ('גבעת אולגה'), ('אור עקיבא')
  ) as c(city)
 where b.name = 'חיפה והצפון'
on conflict (branch_id, city) do nothing;


-- ---------------------------------------------------------------------
-- כמה נכנסו
-- ---------------------------------------------------------------------

select b.name                                        as "סניף",
       count(bc.city)                                as "יישובים ברשימה",
       (select count(*) from people_for_branch(b.id)) as "פעילים ברשימה"
  from branches b
  left join branch_cities bc on bc.branch_id = b.id
 group by b.id, b.name
 order by b.covers_all desc;


-- ---------------------------------------------------------------------
-- יישובים שקיימים בנתונים ואינם משויכים לאף סניף
--
-- עבור על הפלט: דרומיים זה תקין, צפוניים שלא זיהינו — להוסיף למעלה.
-- ---------------------------------------------------------------------

select city_of(p.notes)                         as "יישוב לא משויך",
       count(*)                                 as "כמה פעילים"
  from people p
 where p.status = 'active' and p.do_not_contact = false
   and city_of(p.notes) is not null
   and not exists (
     select 1 from branch_cities bc where bc.city = city_of(p.notes)
   )
 group by 1
 order by 2 desc
 limit 60;
